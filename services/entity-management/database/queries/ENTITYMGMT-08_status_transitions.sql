-- ============================================================================
-- Query 5: Raw status update SQL (reference implementation)
--
-- The core SQL that powers update_entity_optimistic for status transitions.
-- The trigger prevent_immutable_field_update now allows active↔inactive.
--
--   UPDATE entities
--   SET
--       status     = 'inactive'::entity_status,
--       version    = version + 1,
--       updated_at = NOW()
--   WHERE id = 'e0800001-0000-4000-8000-000000000001'
--     AND version = 3          -- Optimistic lock
--   RETURNING *;
--
-- This will succeed for active→inactive or inactive→active.
-- This will FAIL (trigger RAISEs) for deleted→anything-via-update.
-- ============================================================================

