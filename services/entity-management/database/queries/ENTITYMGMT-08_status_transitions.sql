-- ============================================================================
-- Queries: ENTITYMGMT-08 — Entity Status Lifecycle Enforcement
-- Bounded Context: Entity Management
--
-- This file documents the primary SQL query patterns used for status
-- lifecycle transitions (active ↔ inactive → deleted terminal).
--
-- Gherkin SCENARIO 1: active → inactive (success)
-- Gherkin SCENARIO 2: inactive → active (success)
-- Gherkin SCENARIO 3: active → deleted (soft-delete via DELETE endpoint)
-- Gherkin SCENARIO 4: deleted → active via update (REJECTED)
-- Gherkin SCENARIO 5: invalid status value (REJECTED)
-- ============================================================================

-- ============================================================================
-- Query 1: Validate status transition (read-only, no modification)
--
-- Pre-checks whether a status transition is valid according to the lifecycle:
--   active ↔ inactive → deleted (terminal)
--
-- This is a STABLE function that does not modify any data. It can be called
-- from the application layer to validate transitions before performing
-- the actual update.
--
-- Gherkin SCENARIO 1 (valid):
--   SELECT * FROM validate_status_transition(
--     p_current_status := 'active'::entity_status,
--     p_new_status     := 'inactive'::entity_status,
--     p_via_restore    := FALSE
--   );
--   → is_valid = TRUE, error_code = NULL
--
-- Gherkin SCENARIO 4 (invalid):
--   SELECT * FROM validate_status_transition(
--     p_current_status := 'deleted'::entity_status,
--     p_new_status     := 'active'::entity_status,
--     p_via_restore    := FALSE
--   );
--   → is_valid = FALSE, error_code = 'ERR_INVALID_STATUS_TRANSITION'
--     error_message includes "restore endpoint"
--
-- Gherkin SCENARIO 4 via restore (valid):
--   SELECT * FROM validate_status_transition(
--     p_current_status := 'deleted'::entity_status,
--     p_new_status     := 'active'::entity_status,
--     p_via_restore    := TRUE
--   );
--   → is_valid = TRUE (restore is the only way out of deleted)
--
-- Gherkin SCENARIO 5 (invalid value):
--   The entity_status ENUM rejects 'unknown' at the type level before
--   any function is called. You cannot even pass it as a parameter:
--   SELECT * FROM validate_status_transition(
--     p_current_status := 'active'::entity_status,
--     p_new_status     := 'unknown'::entity_status  -- PG ERROR!
--   );
-- ============================================================================

-- ============================================================================
-- Query 2: Status-only update via dedicated function
--
-- The recommended way to perform a status-only update. This function
-- validates the transition, applies it atomically with optimistic
-- concurrency, and enqueues the entitymanagement.entity.updated outbox
-- event with previous_status and new_status in the payload.
--
-- Gherkin SCENARIO 1 (active → inactive):
--   SELECT * FROM update_entity_status_with_outbox(
--     p_entity_id         := 'e0800001-0000-4000-8000-000000000001',
--     p_expected_version  := 3,
--     p_new_status        := 'inactive'::entity_status
--   );
--
-- Expected result (SCENARIO 1):
--   success          = TRUE
--   changed_fields   = ARRAY['status', 'version']
--   error_code       = NULL
--   event_id         = <uuid>
--   Entity JSON contains:
--     status → "inactive"
--     version → 4
--
-- Gherkin SCENARIO 2 (inactive → active):
--   SELECT * FROM update_entity_status_with_outbox(
--     p_entity_id         := 'e0800001-0000-4000-8000-000000000002',
--     p_expected_version  := 2,
--     p_new_status        := 'active'::entity_status
--   );
--
-- Expected result (SCENARIO 2):
--   success          = TRUE
--   changed_fields   = ARRAY['status', 'version']
--   error_code       = NULL
--   event_id         = <uuid>
--   Entity JSON contains:
--     status → "active"
--     version → 3
--
-- Gherkin SCENARIO 4 (deleted → active — REJECTED):
--   SELECT * FROM update_entity_status_with_outbox(
--     p_entity_id         := 'e0800001-0000-4000-8000-000000000003',
--     p_expected_version  := 4,
--     p_new_status        := 'active'::entity_status
--   );
--
-- Expected result (SCENARIO 4):
--   success          = FALSE
--   error_code       = 'INVALID_STATUS_TRANSITION'
--   event_id         = NULL  (NO event emitted)
--   entity_json      = NULL  (NO data modified)
--   error_message    includes "restore endpoint"
-- ============================================================================

-- ============================================================================
-- Query 3: Combined update (name + status + attributes) via general function
--
-- When multiple fields change at once (e.g., name AND status), use the
-- general update_entity_with_outbox() function. It now passes previous_status
-- and new_status to the enhanced outbox event automatically.
--
-- Usage:
--   SELECT * FROM update_entity_with_outbox(
--     p_entity_id         := 'e0800001-0000-4000-8000-000000000001',
--     p_expected_version  := 4,
--     p_name              := 'Alice Updated',
--     p_status            := 'active'::entity_status,
--     p_attributes        := '{"email": "alice.new@example.com"}'::jsonb
--   );
--
-- Expected result:
--   success          = TRUE
--   changed_fields   = ARRAY['name', 'status', 'attributes.email', 'version']
--   event_id         = <uuid>
--   Outbox payload includes:
--     previous_status = "inactive"
--     new_status      = "active"
--     changed_fields  = ["name", "status", "attributes.email", "version"]
