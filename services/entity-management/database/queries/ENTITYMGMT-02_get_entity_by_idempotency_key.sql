-- Story: ENTITYMGMT-02 — User creates an entity with idempotency support (7-day TTL)
-- Bounded Context: Entity Management
--
-- Gherkin SCENARIO 2: Retrieves the previously created entity for a given
-- idempotency key. Used to handle duplicate create requests idempotently.
--
-- If the key exists and has not expired, the full entity is returned.
-- If the key does not exist or has expired, no rows are returned.
--
-- Gherkin SCENARIO 3: An expired key returns no rows, and the application
-- treats it as a new creation request.
--
-- Usage:
--   SELECT * FROM get_entity_by_idempotency_key('create-customer-001');
--   -- Returns entity if key is valid (within 7-day TTL)
--   -- Returns no rows if key is expired or never existed
-- ============================================================================

-- :name get-entity-by-idempotency-key
-- :command :query
-- :result :one
SELECT * FROM get_entity_by_idempotency_key($1::TEXT);
